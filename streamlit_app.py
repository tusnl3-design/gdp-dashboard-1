# ---------------------------------------------------------
# 1. API 데이터 수집 함수 (B552481 DerivesSvc 규격 적용)
# ---------------------------------------------------------
@st.cache_data(ttl=3600)
def fetch_els_data(service_key):
    # 캡처 화면의 End Point 주소 반영
    url = "https://apis.data.go.kr/B552481/DerivesSvc/getElsOfrList"
    
    params = {
        "serviceKey": service_key,
        "pageNo": "1",
        "numOfRows": "30"
    }
    
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36"
    }
    
    try:
        response = requests.get(url, params=params, headers=headers, timeout=10)
        
        if response.status_code == 200:
            # XML 응답 파싱
            root = ET.fromstring(response.text)
            
            # 결과 코드 확인
            result_code = root.find(".//resultCode")
            result_msg = root.find(".//resultMsg")
            
            if result_code is not None and result_code.text != "00":
                return pd.DataFrame(), f"API 오류 ({result_code.text}): {result_msg.text if result_msg is not None else ''}"
            
            items = root.findall(".//item")
            if not items:
                return pd.DataFrame(), "현재 조회된 공모 ELS 데이터가 없습니다."
            
            parsed_list = []
            for item in items:
                def get_txt(tag_name, default_val="-"):
                    node = item.find(tag_name)
                    return node.text.strip() if node is not None and node.text else default_val

                sec_company = get_txt("issuCoNm", "증권사")
                item_name = get_txt("isinNm", "ELS 상품")
                underlying = get_txt("kndNm", "지수/종목")
                ki = get_txt("bareAt", "50%")
                due_date = get_txt("subEndDt", today_str)
                
                # 수익률 숫자 변환
                try:
                    rate = float(get_txt("expYidRt", "0.0"))
                except:
                    rate = 0.0

                # KI 숫자 변환
                try:
                    ki_num = int(ki.replace("%", ""))
                except:
                    ki_num = 50

                els_type = "종목형" if any(k in underlying for k in ["삼성", "SK", "테슬라", "엔비디아", "NAVER", "카카오", "현대"]) else "지수형"

                parsed_list.append({
                    "유형": els_type,
                    "증권사": sec_company,
                    "종목명": item_name,
                    "기초자산": underlying,
                    "낙인(KI)": ki,
                    "KI_num": ki_num,
                    "제시수익률(연)": rate,
                    "청약마감일": due_date
                })
            
            return pd.DataFrame(parsed_list), None
        else:
            return pd.DataFrame(), f"서버 응답 에러 (상태 코드: {response.status_code})"
            
    except Exception as e:
        return pd.DataFrame(), f"데이터를 불러오는 중 오류가 발생했습니다: {str(e)}"

